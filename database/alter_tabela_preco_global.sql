) v
WHERE NOT EXISTS (SELECT 1 FROM tabela_preco_margens_cfg LIMIT 1);

INSERT INTO tabela_preco_qtd_cfg (quantidade, ordem)
SELECT v.q, v.o FROM (
  SELECT 10 AS q, 0 AS o UNION ALL
